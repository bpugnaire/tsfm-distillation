def gallery() -> dict:
    d = ROOT / "results" / "shapes"
    suite = json.loads((d / "_suite.json").read_text())
    runs = load_runs(d)
    idx_levels = [QUANTILE_LEVELS.index(lv) for lv in SHOWN]
    shapes, rows = [], []
    for k, sid in enumerate(suite["ids"]):
        name, seed = sid.split("#")
        if seed != "0":
            continue
        meta = suite["meta"][k]
        shapes.append(
            {
                "name": name,
                "description": describe(name),
                "period": meta["period"],
                "context": [sig(v) for v in suite["context"][k]],
                "future": [sig(v) for v in suite["future"][k]],
            }
        )
        rows.append(k)
    models, cells = [], {}
    for m in model_order(list(runs)):
        r = runs[m]
        lat = r.get("latency", {})
        models.append(
            {
                "name": m,
                "role": role_of(m),
                "n_params": r["n_params"],
                "size_mb": r["size_mb"],
                "latency_ms": sig(lat.get("threads1_batch1", {}).get("p50_ms"), 3),
                "tails_extrapolated": len(r["native_levels"]) < len(QUANTILE_LEVELS),
                "fallbacks": r.get("fallbacks", []),
            }
        )
        cells[m] = {
            suite["ids"][k].split("#")[0]: {
                "q": [
                    [sig(v) for v in np.array(r["forecasts_f16"][k], dtype=float)[i]]
                    for i in idx_levels
                ],
                "wql": sig(r["per_series"]["wql"][k]),
                "mase": sig(r["per_series"]["mase"][k]),
            }
            for k in rows
        }
    return {
        "levels": list(SHOWN),
        "shapes": shapes,
        "models": models,
        "cells": cells,
        "hardware": runs["seasonal_naive"]["hardware"],
    }


def per_shape_table(d: Path) -> dict:
    runs = load_runs(d)
    ids = runs["seasonal_naive"]["ids"]
    base = np.array(
        [np.nan if v is None else v for v in runs["seasonal_naive"]["per_series"]["wql"]]
    )
    out = {}
    for m in model_order(list(runs)):
        w = np.array([np.nan if v is None else v for v in runs[m]["per_series"]["wql"]])
        per = {}
        for sh in dict.fromkeys(i.split("#")[0] for i in ids):
            sel = [k for k, i in enumerate(ids) if i.split("#")[0] == sh]
            rel = w[sel] / base[sel]
            rel = rel[np.isfinite(rel) & (rel > 0)]
            per[sh] = sig(float(np.exp(np.log(rel).mean())), 3)
        out[m] = per
    return out


def crps_bias() -> dict:
    """E[2 * mean_k rho_k] for a calibrated N(0,1) forecast, vs exact CRPS = 1/sqrt(pi)."""
    exact = 1 / math.sqrt(math.pi)

    def eq(levels):
        return float(2 * np.mean(norm.pdf(norm.ppf(levels))))

    def mass(levels):
        lv = np.asarray(levels)
        edges = np.concatenate([[0], (lv[1:] + lv[:-1]) / 2, [1]])
        return float(2 * np.sum(np.diff(edges) * norm.pdf(norm.ppf(lv))))

    grids = {
        "9 levels (GIFT-Eval)": CORE_LEVELS,
        "13 levels (ours)": QUANTILE_LEVELS,
        "99 uniform levels": tuple(np.arange(1, 100) / 100),
    }
    return {
        "exact": exact,
        "equal_weights": {k: eq(v) for k, v in grids.items()},
        "mass_weights": {k: mass(v) for k, v in grids.items()},
    }


def results() -> dict:
    out = {"suites": {}, "per_shape": {}, "splits": {}, "export": {}, "throughput": {}}
    for s in ("fresh_fr_power", "shapes", "multidomain_test"):
        p = ROOT / "results" / s / "summary.json"
        if p.exists():
            summ = json.loads(p.read_text())
            for r in summ["rows"]:
                r["role"] = role_of(r["model"])
            out["suites"][s] = summ
            out["per_shape"][s] = per_shape_table(ROOT / "results" / s) if s == "shapes" else None
    sp = load_splits()
    out["splits"] = {
        "train_end": str(sp.train_end.date()),
        "val_start": str(sp.val_start.date()),
        "val_end": str(sp.val_end.date()),
        "fresh_start": str(sp.fresh_start.date()),
        "releases": {k: str(v.date()) for k, v in sp.model_releases.items()},
    }
    for p in sorted((ROOT / "results" / "export").glob("*.json")):
        out["export"][p.stem] = json.loads(p.read_text())
    tp = ROOT / "results" / "throughput.json"
    out["throughput"] = json.loads(tp.read_text()) if tp.exists() else {}
    out["crps_bias"] = crps_bias()
    return out


def status() -> dict:
    """PLAN.md checkboxes per phase + docs/status.yaml + journal headlines + artifacts."""
    import re

    plan = (ROOT / "PLAN.md").read_text()
    phases = []
    for block in re.split(r"(?m)^## ", plan)[1:]:
        title = block.splitlines()[0].strip()
        if not title.lower().startswith("phase"):
            continue
        items = []
        section = ""
        for ln in block.splitlines()[1:]:
            if ln.startswith("### "):
                section = ln[4:].strip()
            m = re.match(r"^- \[( |x|~)\] (.*)", ln.strip())
            if m:
                text = re.sub(r"[*`]", "", m.group(2)).strip()
                items.append(
                    {
                        "state": {"x": "done", " ": "todo", "~": "superseded"}[m.group(1)],
                        "text": text,
                        "section": section,
                    }
                )
        phases.append({"title": title, "items": items})
    journal = []
    for block in re.split(r"(?m)^## ", (ROOT / "docs" / "journal.md").read_text())[1:]:
        head = block.splitlines()[0].strip()
        nxt = re.search(r"\*\*Next[^*]*\*\*\s*(.*)", block, re.S)
        journal.append(
            {"title": head, "next": (nxt.group(1).strip().split("\n\n")[0] if nxt else "")}
        )
    models = []
    for p in sorted((WEB / "public" / "models").glob("*.onnx")):
        models.append({"file": p.name, "size_mb": round(p.stat().st_size / 1e6, 2)})
    st = yaml.safe_load((ROOT / "docs" / "status.yaml").read_text())
    return {"phases": phases, "journal": journal, "models": models, **st}


