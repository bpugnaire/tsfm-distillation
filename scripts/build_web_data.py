def _study_pair(stage: str, a: str, b: str, suites=SUITES) -> list[dict]:
    t = ROOT / "results" / "study" / stage / "table.json"
    tab = read(t)["suites"]
    out = []
    for s in suites:
        p = next((p for p in tab.get(s, {}).get("pairs", []) if p["a"] == a and p["b"] == b), None)
        if p is None:
            continue
        out.append({"suite": s, "name": SUITE_NAMES[s], "ratio": p["ratio"], "source": rel(t)})
    if not out:
        raise KeyError(f"{stage}: no pair {a} vs {b}")
    return out


def _site_pair(a: str, b: str) -> list[dict]:
    p = ROOT / "results" / "site_pairs.json"
    return [{"suite": r["suite"], "name": SUITE_NAMES[r["suite"]], "ratio": r["ratio"], "source": rel(p)}
            for r in read(p) if r["a"] == a and r["b"] == b]  # fmt: skip


