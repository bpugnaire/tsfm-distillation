def sig(x, n=4):
    if x is None or not math.isfinite(x):
        return None
    if x == 0:
        return 0.0
    return round(x, -int(math.floor(math.log10(abs(x)))) + (n - 1))


def load_runs(d: Path) -> dict:
    return {
        json.loads(p.read_text())["model"]: json.loads(p.read_text())
        for p in sorted(d.glob("*.json"))
        if not p.name.startswith(("_", "summary"))
    }


def model_order(names):
    rest = sorted(n for n in names if n not in ORDER)
    return [n for n in ORDER if n in names] + rest


