def code_snippets() -> dict:
    """Source of the functions the Learn pages show, extracted from the repo (never stale)."""
    import importlib
    import inspect

    out = {}
    for ref in CODE_REFS:
        parts = ref.split(".")
        for k in range(len(parts) - 1, 0, -1):
            try:
                obj = importlib.import_module(".".join(parts[:k]))
                for attr in parts[k:]:
                    obj = getattr(obj, attr)
                break
            except (ImportError, AttributeError):
                continue
        else:
            raise ImportError(ref)
        src = inspect.getsource(obj)
        file = inspect.getsourcefile(obj)
        out[ref] = {
            "file": str(Path(file).relative_to(ROOT)),
            "line": inspect.getsourcelines(obj)[1],
            "code": inspect.cleandoc(src) if src.startswith(" ") else src,
        }
    return out


