def label(m: str) -> str:
    if m in LABELS:
        return LABELS[m]
    if m.startswith("toto-2.0-"):
        return "Toto-2.0-" + m.removeprefix("toto-2.0-")
    if m.startswith("timestral-"):
        return "Timestral-" + m.removeprefix("timestral-").upper()
    return m


def role(m: str) -> str:
    if m == STUDENT["teacher"]:
        return "teacher"
    if m == "student-gt":
        return "baseline"
    r = role_of(m)
    return "comparator" if r == "teacher" else r  # other teachers of the study are comparators here


def sig(x, n=4):
    if x is None or not math.isfinite(x):
        return None
    if x == 0:
        return 0.0
    return round(x, -int(math.floor(math.log10(abs(x)))) + (n - 1))


def read(p: Path) -> dict:
    return json.loads(p.read_text())


def rel(p: Path) -> str:
    return str(p.relative_to(ROOT))


def palette_ts() -> None:
    st = yaml.safe_load((ROOT / "configs" / "style.yaml").read_text())
    body = "// GENERATED by scripts/build_web_data.py from configs/style.yaml. Do not edit.\n"
