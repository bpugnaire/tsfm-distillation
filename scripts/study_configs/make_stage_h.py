"""Generates configs/study/stage_h_fresh_multi.yaml. Run: python scripts/study_configs/make_stage_h.py

Stage H (owner 2026-11-28): does Stage G's headline hold beyond pedestrians? Three more fresh datasets with different
shapes (French solar and wind production, Paris bike counters; targets after every model's release). PRE-REGISTERED
headline arm, the same as Stage G and fixed before any result: replay_<d>_1y (replay, 1 year of history; Paris counters
have 11.5 months) vs each model zero-shot. For context: full fine-tuning and teacher-label fine-tuning at 1 year.
Starting model, steps rule, seeds and forgetting suites as Stage F/G.
"""

from pathlib import Path

import yaml

INIT = "stage_c15_3m:kd5m_3m"
POOL = "replay_pool_timestral-5m_48dd0113d4.npz"
D = {
    "solar": ("fr_solar", "fresh_fr_solar"),
    "wind": ("fr_wind", "fresh_fr_wind"),
    "bike": ("paris_bike", "fresh_paris_bike"),
}
GENERAL = ["shapes", "multidomain_test"]
TECH = {
    "replay": {"lr": 3e-4, "replay": 0.5, "replay_pool": POOL},
    "full": {"lr": 3e-4},
    "kd": {"lr": 3e-4, "teacher": "timestral-5m", "alpha": 1.0},
}
ZOO = ["seasonal_naive", "toto-2.0-4m", "toto-2.0-22m", "toto-2.0-313m", "timestral-5m", "timestral-28m",
       "timestral-209m", "chronos-2", "t0-gamma"]  # fmt: skip
arms = [{"name": "zero_shot", "type": "existing", "run": INIT}]
pairs, suites = [], set(GENERAL)
for d, (domain, test) in D.items():
    suites.add(test)
    for t, opts in TECH.items():
        name = f"{t}_{d}_1y"
        arms.append({"name": name, "type": "finetune", "mode": "warm", "seeded": True, "domain": domain, "history": 8760,
                     "init": INIT, "student_from": INIT, "steps": 1500, "epochs": 20, "eval_suites": [test, *GENERAL],
                     **opts})  # fmt: skip
        pairs.append([name, "zero_shot", f"{domain} 1y: {t} vs zero-shot student"])
        for z in ZOO[1:]:
            pairs.append([name, f"zoo:{z}", f"{domain} 1y: {t} fine-tuning vs {z} zero-shot"])
study = {
    "name": "stage_h_fresh_multi", "base": "configs/train/study_base_m.yaml", "reference_arm": "zero_shot",
    "seeds": [0, 1, 2], "zoo": ZOO, "eval_suites": sorted(suites), "arms": arms, "pairs": pairs,
}  # fmt: skip
if __name__ == "__main__":
    Path("configs/study/stage_h_fresh_multi.yaml").write_text(
        "# GENERATED by scripts/study_configs/make_stage_h.py (see its docstring): edit the script, not this file.\n"
        + yaml.safe_dump(study, sort_keys=False, width=140)
    )
