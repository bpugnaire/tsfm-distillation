"""Stage G (owner 2026-11-27): Stage F repeated on FRESH pedestrian counts (City of Melbourne, targets after every
model's release, fine-tuning history = the year before). PRE-REGISTERED headline arm, fixed before any result on this
suite: replay_mel_1y (replay, 1 year of history; the technique Stage F recommended, chosen on other test sets) vs each
teacher zero-shot. Everything below is otherwise identical to Stage F.

Generates configs/study/stage_g_fresh_ped.yaml. Run: python scripts/study_configs/make_stage_g.py

Stage F (owner 2026-11-23): what does fine-tuning a small foundation forecaster on your own history buy, and what does it
cost elsewhere? Starting model: the site student (C15 kd5m_3m, 0.87M, 3M windows, Timestral-5M labels).
- Target domains (both clean): fresh French electricity (after every model's release) and Melbourne pedestrian counts
  (held out of distillation). Warm mode: the full past may serve as context; fine-tuning targets lie in the last
  1 week / 1 month / 1 year before the test period. 3 seeds per arm (init noise / batch order; same windows).
- Techniques, all fixed before any result (no tuning on the test sets):
    full        all weights, lr 3e-4 (Stage D's setting)
    full_lowlr  all weights, lr 1e-4
    head        output head only (27k of 867k weights), lr 1e-3
    last        head + last encoder layer + final norm, lr 3e-4
    l2sp_s      L2-SP anchor to the distilled weights, weight 1e-3 (penalty ~10% of the loss at full fine-tuning's drift)
    l2sp_l      L2-SP, weight 1e-2 (penalty ~ the loss at that drift)
    replay      50% of training windows replayed from the distillation data with their teacher labels
    kd          target history labelled by the teacher (Timestral-5M) instead of the real future
    scratch     same architecture from random weights, lr 1e-3 (does pretraining matter at this history?)
- Steps: 20 epochs over the fine-tuning windows, between 100 and 1500 (Stage D's rule); early stopping on the last 20%
  of the history (never the test).
- Evaluated on the target's test set AND on shapes + held-out public data (multidomain_test): forgetting.
"""

from pathlib import Path

import yaml

INIT = "stage_c15_3m:kd5m_3m"
POOL = "replay_pool_timestral-5m_48dd0113d4.npz"
H = {"1w": 168, "1m": 720, "1y": 8760}
D = {"mel": ("mel_ped", "fresh_mel_ped")}
GENERAL = ["shapes", "multidomain_test"]
TECH = {
    "full": {"lr": 3e-4},
    "full_lowlr": {"lr": 1e-4},
    "head": {"lr": 1e-3, "trainable": "head"},
    "last": {"lr": 3e-4, "trainable": "last"},
    "l2sp_s": {"lr": 3e-4, "l2sp": 1e-3},
    "l2sp_l": {"lr": 3e-4, "l2sp": 1e-2},
    "replay": {"lr": 3e-4, "replay": 0.5, "replay_pool": POOL},
    "kd": {"lr": 3e-4, "teacher": "timestral-5m", "alpha": 1.0},
    "scratch": {"lr": 1e-3, "init": "scratch"},
}
ZOO = [
    "seasonal_naive",
    "toto-2.0-4m",
    "toto-2.0-22m",
    "toto-2.0-313m",
    "timestral-5m",
    "timestral-28m",
    "timestral-209m",
    "chronos-2",
    "t0-gamma",
]
arms = [{"name": "zero_shot", "type": "existing", "run": INIT}]
pairs, suites = [], set(GENERAL)
for d, (domain, test) in D.items():
    suites.add(test)
    for h, steps in H.items():
        for t, opts in TECH.items():
            name = f"{t}_{d}_{h}"
            ev = [test] if t == "scratch" else [test, *GENERAL]
            arms.append({"name": name, "type": "finetune", "mode": "warm", "seeded": True, "domain": domain,
                         "history": steps, "init": INIT, "student_from": INIT, "steps": 1500, "epochs": 20,
                         "eval_suites": ev, **opts})  # fmt: skip
            pairs.append([name, "zero_shot", f"{domain} {h}: {t} vs zero-shot student"])
            if t != "full":
                pairs.append([name, f"full_{d}_{h}", f"{domain} {h}: {t} vs full fine-tuning"])
        for z in ZOO[1:]:
            for t in (
                "full",
                "replay",
            ):  # replay_*_1y vs every teacher is the pre-registered headline
                pairs.append(
                    [f"{t}_{d}_{h}", f"zoo:{z}", f"{domain} {h}: {t} fine-tuning vs {z} zero-shot"]
                )
study = {
    "name": "stage_g_fresh_ped", "base": "configs/train/study_base_m.yaml", "reference_arm": "zero_shot",
    "seeds": [0, 1, 2], "zoo": ZOO, "eval_suites": sorted(suites), "arms": arms, "pairs": pairs,
}  # fmt: skip
HEADER = "# GENERATED by scripts/study_configs/make_stage_g.py (see its docstring): edit the script, not this file.\n"
if __name__ == "__main__":
    Path("configs/study/stage_g_fresh_ped.yaml").write_text(
        HEADER + yaml.safe_dump(study, sort_keys=False, width=140)
    )
