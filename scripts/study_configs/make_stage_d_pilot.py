"""Generates configs/study/stage_d_pilot.yaml (12 fine-tuning arms + paired contrasts). Run: python scripts/study_configs/make_stage_d_pilot.py"""

import yaml

H = {"1w": 168, "1m": 720, "1y": 8760}
D = {"fr": ("fr_power", "fresh_fr_power"), "ped": ("pedestrian", "pedestrian_test")}
arms = [{"name": "distilled_zero_shot", "type": "existing", "run": "stage_a:kd_multidomain"}]
pairs = []
for d, (domain, suite) in D.items():
    for h, steps in H.items():
        for init, lr in (("distilled", 3e-4), ("scratch", 1e-3)):
            arms.append({
                "name": f"ft_{d}_{h}_{init}", "type": "finetune", "domain": domain, "history": steps,
                "init": "stage_a:kd_multidomain" if init == "distilled" else "scratch",
                "student_from": "stage_a:kd_multidomain", "steps": 1000, "lr": lr, "eval_suites": [suite],
            })  # fmt: skip
        pairs.append(
            [
                f"ft_{d}_{h}_distilled",
                f"ft_{d}_{h}_scratch",
                f"{domain} {h}: distilled init vs scratch",
            ]
        )
        pairs.append(
            [
                f"ft_{d}_{h}_distilled",
                "distilled_zero_shot",
                f"{domain} {h}: fine-tuned vs not fine-tuned",
            ]
        )
        for z in ("timestral-209m", "toto-2.0-313m", "timestral-5m", "toto-2.0-4m"):
            pairs.append(
                [
                    f"ft_{d}_{h}_distilled",
                    f"zoo:{z}",
                    f"{domain} {h}: fine-tuned student vs {z} zero-shot",
                ]
            )
study = {"name": "stage_d_pilot", "base": "configs/train/study_base_s.yaml", "reference_arm": "distilled_zero_shot",
         "eval_suites": ["fresh_fr_power", "pedestrian_test"], "arms": arms, "pairs": pairs}  # fmt: skip
HEADER = (
    "# Stage D PILOT (RQ6, headline): light fine-tuning on a target domain's own history (ground truth only),\n"
    "# from the Stage-A student selected on VALIDATION (kd_multidomain, val WQL 0.144) vs from scratch (same architecture).\n"
    "# lr: 3e-4 when fine-tuning a trained model, 1e-3 from scratch (each its usual rate). 1 seed (pilot).\n"
    "# GENERATED by scripts/study_configs/make_stage_d_pilot.py: edit the script, not this file.\n"
)
if __name__ == "__main__":
    from pathlib import Path

    Path("configs/study/stage_d_pilot.yaml").write_text(
        HEADER + yaml.safe_dump(study, sort_keys=False, width=140)
    )
