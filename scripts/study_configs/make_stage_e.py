"""Generates configs/study/stage_e.yaml. Run: python scripts/study_configs/make_stage_e.py

Stage E (RQ6 bis): fine-tune on YOUR history with TEACHER labels instead of (or mixed with) its raw future.
Same as final Stage D warm (init = C-lite student chosen on validation, histories 1 week / 1 month / 1 year, 20 epochs capped
at 1500 steps, lr 3e-4, 3 seeds); only the target changes: Timestral-209M's forecast of each history window (alpha = 1) or a
50/50 mix with the real future (alpha = 0.5). References: the Stage-D ground-truth fine-tunes (same seeds) and the zero-shot student.
Prediction (journal 2026-11-13): teacher labels remove most of the harm of a 1-month fine-tune on electricity.
"""

from pathlib import Path

import yaml

INIT = "best_val:stage_c_lite+stage_b"
H = {"1w": 168, "1m": 720, "1y": 8760}
D = {"fr": ("fr_power", "fresh_fr_power"), "ped": ("pedestrian", "pedestrian_test")}
arms = [{"name": "zero_shot", "type": "existing", "run": INIT}]
pairs = []
for d, (domain, suite) in D.items():
    for h, steps in H.items():
        for seed in (0, 1, 2):
            arms.append(
                {
                    "name": f"gt_{d}_{h}_s{seed}",
                    "type": "existing",
                    "run": f"stage_d_final:ft_warm_{d}_{h}_distilled_s{seed}",
                    "eval_suites": [suite],
                }
            )
        for alpha, tag in ((1.0, "kd"), (0.5, "mix")):
            arms.append({
                "name": f"{tag}_{d}_{h}", "type": "finetune", "mode": "warm", "seeded": True, "teacher": "timestral-209m",
                "alpha": alpha, "domain": domain, "history": steps, "init": INIT, "student_from": INIT,
                "steps": 1500, "epochs": 20, "lr": 3e-4, "eval_suites": [suite],
            })  # fmt: skip
        pairs += [
            [
                f"kd_{d}_{h}",
                f"gt_{d}_{h}",
                f"{domain} {h}: teacher labels vs real future (fine-tuning target)",
            ],
            [f"mix_{d}_{h}", f"gt_{d}_{h}", f"{domain} {h}: 50/50 mix vs real future"],
            [f"kd_{d}_{h}", "zero_shot", f"{domain} {h}: teacher-label fine-tune vs no fine-tune"],
        ]
        for z in ("toto-2.0-4m", "timestral-5m", "timestral-209m"):
            pairs.append(
                [
                    f"kd_{d}_{h}",
                    f"zoo:{z}",
                    f"{domain} {h}: teacher-label fine-tune vs {z} zero-shot",
                ]
            )
            pairs.append(
                [f"mix_{d}_{h}", f"zoo:{z}", f"{domain} {h}: 50/50-mix fine-tune vs {z} zero-shot"]
            )
    # data efficiency (added after the first read of the results): teacher labels on 1 month vs real future on 1 year
    pairs.append(
        [
            f"kd_{d}_1m",
            f"gt_{d}_1y",
            f"{domain}: teacher labels on 1 month vs real future on 1 year",
        ]
    )
study = {"name": "stage_e", "base": "configs/train/study_base_s.yaml", "reference_arm": "zero_shot", "seeds": [0, 1, 2],
         "eval_suites": ["fresh_fr_power", "pedestrian_test"], "arms": arms, "pairs": pairs}  # fmt: skip
HEADER = "# GENERATED by scripts/study_configs/make_stage_e.py (see its docstring): edit the script, not this file.\n"
if __name__ == "__main__":
    Path("configs/study/stage_e.yaml").write_text(
        HEADER + yaml.safe_dump(study, sort_keys=False, width=140)
    )
