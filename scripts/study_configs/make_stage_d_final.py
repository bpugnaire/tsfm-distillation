"""Generates configs/study/stage_d_final.yaml. Run: python scripts/study_configs/make_stage_d_final.py

Final Stage D (headline, RQ6). Starting student = best VALIDATION score among Stage C-lite and Stage B runs.
- warm (main): full past available as context, fine-tuning targets limited to the last week / month / year; 3 seeds.
- cold start: only that week / month exists (contexts too), evaluated on test windows whose contexts are cut the same way,
  where the zero-shot models also only see that much (suites "<suite>@<steps>"); 1 seed.
Steps = 20 epochs over the fine-tuning windows, capped at 1500 (pilot: fixed 1000 steps overfit short histories).
"""

from pathlib import Path

import yaml

INIT = "best_val:stage_c_lite+stage_b"
H = {"1w": 168, "1m": 720, "1y": 8760}
D = {"fr": ("fr_power", "fresh_fr_power"), "ped": ("pedestrian", "pedestrian_test")}
ZOO = ["seasonal_naive", "toto-2.0-4m", "timestral-5m", "toto-2.0-313m", "timestral-209m"]
arms = [{"name": "distilled_zero_shot", "type": "existing", "run": INIT}]
pairs, suites = [], set()
for d, (domain, suite) in D.items():
    suites.add(suite)
    for h, steps in H.items():
        for mode in ("warm", "cold"):
            if mode == "cold" and h == "1y":
                continue  # a year of context is the full 512 steps: cold == warm
            test = suite if mode == "warm" else f"{suite}@{steps}"
            suites.add(test)
            for init, lr in (("distilled", 3e-4), ("scratch", 1e-3)):
                arms.append({
                    "name": f"ft_{mode}_{d}_{h}_{init}", "type": "finetune", "mode": mode, "seeded": mode == "warm",
                    "domain": domain, "history": steps, "init": INIT if init == "distilled" else "scratch",
                    "student_from": INIT, "steps": 1500, "epochs": 20, "lr": lr, "eval_suites": [test],
                })  # fmt: skip
            a = f"ft_{mode}_{d}_{h}_distilled"
            pairs.append(
                [a, f"ft_{mode}_{d}_{h}_scratch", f"{mode} {domain} {h}: distilled init vs scratch"]
            )
            if mode == "warm":
                pairs.append(
                    [
                        a,
                        "distilled_zero_shot",
                        f"warm {domain} {h}: fine-tuned vs zero-shot student",
                    ]
                )
            for z in ZOO[1:]:
                pairs.append(
                    [a, f"zoo:{z}", f"{mode} {domain} {h}: fine-tuned student vs {z} zero-shot"]
                )
study = {
    "name": "stage_d_final", "base": "configs/train/study_base_s.yaml", "reference_arm": "distilled_zero_shot",
    "seeds": [0, 1, 2], "zoo": ZOO, "eval_suites": sorted(suites), "arms": arms, "pairs": pairs,
}  # fmt: skip
HEADER = "# GENERATED by scripts/study_configs/make_stage_d_final.py (see its docstring): edit the script, not this file.\n"
if __name__ == "__main__":
    Path("configs/study/stage_d_final.yaml").write_text(
        HEADER + yaml.safe_dump(study, sort_keys=False, width=140)
    )
