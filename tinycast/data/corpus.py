"""Deterministic training/validation corpora built from a *mix* of input sources, joined to teacher caches by id.

Sources (counts per source in `CorpusSpec.mix`):
  multidomain  real windows from 11 licensed non-energy datasets (hf_datasets.py), position-based splits
  synth        KernelSynth + randomised shapes + TSMixup (synthetic.py); the generator's true continuation is the future
  rollout      teacher rollouts: a real multidomain start + 1..k blocks generated by a generator teacher with
               correlated sampling (scripts/rollout_study.py); NO ground-truth future (NaN) -> use with alpha = 1
  noise        white noise (negative control); the future is more white noise
  rte          French electricity (only for the final fine-tuning / demonstrator, never for distillation)

A corpus is materialised once into data/processed/corpus_<split>_<key>.npz (regenerable, git-ignored).
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

import numpy as np

from tinycast.data.synthetic import TRAIN_SEED_MAX, synthetic_batch
from tinycast.data.windows import window_id

ROOT = Path(__file__).resolve().parents[2]
SOURCES = ("multidomain", "multidomain_v2", "synth", "rollout", "noise", "rte")


@dataclass(frozen=True)
class CorpusSpec:
    split: str  # train | val
    n_real: int = 0  # legacy: RTE windows
    n_synth: int = 0  # legacy: synthetic windows
    seed: int = 0
    context_length: int = 512
    horizon: int = 64
    mix: tuple[tuple[str, int], ...] = field(
        default_factory=tuple
    )  # (source, count); overrides the legacy fields
    rollout_max_blocks: int = 3
    rollout_generator: str = "mistralai/Timestral-28M"

    def counts(self) -> dict[str, int]:
        if self.mix:
            d = dict(self.mix)
            unknown = set(d) - set(SOURCES)
            if unknown:
                raise ValueError(f"unknown corpus sources {unknown}")
            return d
        return {"rte": self.n_real, "synth": self.n_synth}

    def key(self) -> str:
        return hashlib.sha1(json.dumps(asdict(self), sort_keys=True).encode()).hexdigest()[:10]


@dataclass
class Corpus:
    ids: np.ndarray  # (N,) str
    source: np.ndarray  # (N,) source name
    context: np.ndarray  # (N, T) float32
    future: np.ndarray  # (N, H) float32 (NaN where no ground truth exists, e.g. rollouts)


def _synth_seeds(split: str, n: int, seed: int) -> np.ndarray:
    half = TRAIN_SEED_MAX // 2  # train and val use disjoint seed ranges
    base = 0 if split == "train" else half
    return base + np.random.default_rng([seed, 17]).choice(half, size=n, replace=False)


def _rte(spec: CorpusSpec, n: int):
    from tinycast.data.sources.rte_eco2mix import series_arrays
    from tinycast.data.splits import load_splits
    from tinycast.data.windows import sample_windows

    ws = sample_windows(
        series_arrays(),
        spec.split,
        load_splits(),
        spec.context_length,
        spec.horizon,
        n_windows=n,
        seed=spec.seed,
    )
    return (
        [w.window_id for w in ws],
        np.stack([w.context for w in ws]),
        np.stack([w.future for w in ws]),
    )


def _multidomain(spec: CorpusSpec, n: int, salt: int = 0):
    from tinycast.data.sources import hf_datasets as H

    ctx, fut, ids, _ = H.windows(
        H.load_all(), spec.split, n, spec.seed + 1000 * salt, spec.context_length, spec.horizon
    )
    # with-replacement draws can repeat a window: the draw index keeps ids unique
    return [window_id("md", f"{i}#{j}", salt) for j, i in enumerate(ids)], ctx, fut


def _multidomain_v2(spec: CorpusSpec, n: int):
    """Data v2 (Stage C2): more domains incl. energy, series-level contamination filter, no near-duplicate windows."""
    from tinycast.data.sources import data_v2 as V

    ctx, fut, ids, _, quota = V.windows_v2(
        V.load_v2(), spec.split, n, spec.seed, spec.context_length, spec.horizon
    )
    if len(ids) < n:
        print(
            f"  multidomain_v2: only {len(ids)} distinct windows available (asked {n})", flush=True
        )
    print(f"  multidomain_v2 windows per dataset: {quota}", flush=True)
    return [window_id("md2", i, 0) for i in ids], ctx, fut


def _synth(spec: CorpusSpec, n: int):
    seeds = _synth_seeds(spec.split, n, spec.seed)
    c, f = synthetic_batch(seeds, spec.context_length, spec.horizon)
    return [window_id("synth", str(int(s)), 0) for s in seeds], c, f


def _noise(spec: CorpusSpec, n: int):
    rng = np.random.default_rng([spec.seed, 4242, spec.split == "val"])
    level, scale = rng.uniform(-2, 20, (n, 1)), rng.uniform(0.5, 5, (n, 1))
    x = level + scale * rng.standard_normal((n, spec.context_length + spec.horizon))
    ids = [window_id("noise", f"{spec.split}-{spec.seed}", i) for i in range(n)]
    return (
        ids,
        x[:, : spec.context_length].astype(np.float32),
        x[:, spec.context_length :].astype(np.float32),
    )


def _rollout(spec: CorpusSpec, n: int, log=print):
    """Real multidomain starts (different windows than the 'multidomain' source) + 1..k generated blocks."""
    import torch
    from scipy.stats import norm

    from tinycast.config import ModelEntry
    from tinycast.models import build_model

    _, starts, _ = _multidomain(spec, n, salt=7)
    starts = np.where(np.isnan(starts), np.nanmedian(starts, axis=1, keepdims=True), starts).astype(
        np.float32
    )
    device = (
        "cuda" if torch.cuda.is_available() else "cpu"
    )  # Timestral uses float64 internally: no Apple MPS
    gen = build_model(
        ModelEntry(
            kind="timestral",
            name="generator",
            checkpoint=spec.rollout_generator,
            device=device,
            batch_size=256,
        )
    )
    rng = np.random.default_rng([spec.seed, 99, spec.split == "val"])
    blocks = rng.integers(1, spec.rollout_max_blocks + 1, size=n)
    from tinycast.config import QUANTILE_LEVELS

    lv = np.array(QUANTILE_LEVELS)
    series = starts.copy()
    z = rng.standard_normal(n)
    out_ctx = np.empty_like(starts)
    for b in range(1, spec.rollout_max_blocks + 1):
        q = gen.forecast(series[:, -spec.context_length :], spec.horizon)
        zs = np.empty((n, spec.horizon))
        for t in range(spec.horizon):
            z = 0.9 * z + np.sqrt(1 - 0.81) * rng.standard_normal(n)
            zs[:, t] = z
        u = np.clip(norm.cdf(zs), lv[0], lv[-1])
        idx = np.clip(np.searchsorted(lv, u) - 1, 0, len(lv) - 2)
        w = (u - lv[idx]) / (lv[idx + 1] - lv[idx])
        lo = np.take_along_axis(q, idx[:, None, :], 1)[:, 0]
        hi = np.take_along_axis(q, (idx + 1)[:, None, :], 1)[:, 0]
        series = np.concatenate([series, (lo * (1 - w) + hi * w).astype(np.float32)], axis=1)
        done = blocks == b
        out_ctx[done] = series[done, -spec.context_length :]
        log(f"  rollout block {b}/{spec.rollout_max_blocks}: {int(done.sum())} windows finished")
    ids = [
        window_id("rollout", f"{spec.split}-{spec.seed}-{spec.rollout_generator}", i)
        for i in range(n)
    ]
    return ids, out_ctx, np.full((n, spec.horizon), np.nan, dtype=np.float32)


BUILDERS = {
    "multidomain": _multidomain,
    "multidomain_v2": _multidomain_v2,
    "synth": _synth,
    "noise": _noise,
    "rte": _rte,
    "rollout": _rollout,
}


def build_corpus(spec: CorpusSpec, cache: bool = True, log=print) -> Corpus:
    path = ROOT / "data" / "processed" / f"corpus_{spec.split}_{spec.key()}.npz"
    if cache and path.exists():
        d = np.load(path, allow_pickle=False)
        return Corpus(d["ids"], d["source"], d["context"], d["future"])
    ids, src, ctx, fut = [], [], [], []
    for name, n in spec.counts().items():
        if not n:
            continue
        log(f"  building {n} '{name}' windows ({spec.split})")
        i, c, f = BUILDERS[name](spec, n)
        ids += list(i)
        src += [name] * len(i)
        ctx.append(np.asarray(c, dtype=np.float32))
        fut.append(np.asarray(f, dtype=np.float32))
    if len(set(ids)) != len(ids):
        raise ValueError("duplicate window ids in corpus")
    corpus = Corpus(np.array(ids), np.array(src), np.concatenate(ctx), np.concatenate(fut))
    if cache:
        path.parent.mkdir(parents=True, exist_ok=True)
        np.savez(
            path, ids=corpus.ids, source=corpus.source, context=corpus.context, future=corpus.future
        )
    return corpus
