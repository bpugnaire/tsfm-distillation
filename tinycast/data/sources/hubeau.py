"""French river flow, Hub'Eau hydrometry real-time API (Licence Ouverte v2.0), archived daily.

The API keeps only the last month of real-time readings, so we archive them: `archive()` fetches the last 3 days for a
fixed station list and appends to data/raw/hubeau/<YYYY-MM-DD>.parquet (dedup on load). Station list: 150 stations that
reported flow (Q) in the hour 2026-11-26 00:00-01:00 UTC, stratified by hydrographic basin (first letter of the station
code), seed 0 -> configs/data/hubeau_stations.txt.

    uv run python -m tinycast.data.sources.hubeau select   # once
    uv run python -m tinycast.data.sources.hubeau archive  # daily
"""

from __future__ import annotations

import json
import sys
import time
import urllib.parse
import urllib.request
from datetime import UTC, datetime, timedelta

import numpy as np
import pandas as pd

from tinycast.data.sources.rte_eco2mix import ROOT

API = "https://hubeau.eaufrance.fr/api/v2/hydrometrie/observations_tr"
STATIONS = ROOT / "configs" / "data" / "hubeau_stations.txt"
RAW = ROOT / "data" / "raw" / "hubeau"


def _get(params: dict) -> dict:
    url = f"{API}?{urllib.parse.urlencode(params)}"
    req = urllib.request.Request(url, headers={"User-Agent": "tinycast-research"})
    with urllib.request.urlopen(req, timeout=120) as r:
        return json.load(r)


def select(n: int = 150, seed: int = 0) -> list[str]:
    d = _get({"grandeur_hydro": "Q", "size": 20000, "fields": "code_station",
              "date_debut_obs": "2026-11-26T00:00:00Z", "date_fin_obs": "2026-11-26T01:00:00Z"})  # fmt: skip
    codes = sorted({x["code_station"] for x in d["data"] if x.get("code_station")})
    by_basin: dict[str, list[str]] = {}
    for c in codes:
        by_basin.setdefault(c[0], []).append(c)
    rng = np.random.default_rng(seed)
    share = {b: len(v) / len(codes) for b, v in by_basin.items()}
    pick = []
    for b, v in sorted(by_basin.items()):
        k = max(1, round(n * share[b]))
        pick += sorted(rng.choice(v, size=min(k, len(v)), replace=False).tolist())
    STATIONS.write_text(
        "# GENERATED by tinycast.data.sources.hubeau select (seed 0); see module docstring\n"
        + "\n".join(pick)
        + "\n"
    )
    return pick


def archive(days: int = 3) -> int:
    RAW.mkdir(parents=True, exist_ok=True)
    stations = [s for s in STATIONS.read_text().split() if not s.startswith("#")]
    start = (datetime.now(UTC) - timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")
    rows = []
    for s in stations:
        try:
            d = _get({"code_entite": s, "grandeur_hydro": "Q", "size": 20000, "date_debut_obs": start,
                      "fields": "code_station,date_obs,resultat_obs"})  # fmt: skip
            rows += d["data"]
        except Exception as e:  # one failing station must not stop the archive; logged
            print(f"  {s}: {e}", file=sys.stderr)
        time.sleep(0.2)
    df = pd.DataFrame(rows)
    out = RAW / f"{datetime.now(UTC):%Y-%m-%d}.parquet"
    if out.exists():  # a second run on the same day adds to that day's file, never replaces it
        df = pd.concat([pd.read_parquet(out), df]).drop_duplicates(["code_station", "date_obs"])
    df.to_parquet(out)
    print(
        f"{len(df)} readings from {df['code_station'].nunique() if len(df) else 0} stations -> {out}"
    )
    return len(df)


if __name__ == "__main__":
    {"select": select, "archive": archive}[sys.argv[1]]()
